class TestSingleCycle(BaseTest):
    """A full window archives totals that match the configured rates."""

    @pytest.mark.parametrize(
        (
            "window",
            "days",
            "volume",
            "flagged",
            "blocked",
            "expected_summaries",
            "expected_ratio",
            "expected_total",
            "uid",
        ),
        _SINGLE_CYCLE_CASES,
    )
    def test_single_cycle(
        self,
        window: int,
        days: int,
        volume: int,
        flagged: int,
        blocked: int,
        expected_summaries: int,
        expected_ratio: float,
        expected_total: int,
        uid: int,
    ) -> None:
        """A full window archives totals that match the configured rates."""
        profiler: UserProfiler = UserProfiler(":memory:", ":memory:", window)
        for _ in range(days):
            profiler.record(
                "app",
                "u",
                total_msgs=volume,
                flagged_msgs=flagged,
                blocked_msgs=blocked,
            )
            self.advance_days(1)
        profile = profiler.get_profile("app", "u")
        assert len(profile["summaries"]) == expected_summaries
        assert profiler.get_ratio("app", "u") == expected_ratio
        summary = profile["summaries"][0]
        assert summary["total_msgs"] == expected_total
        profiler.close()

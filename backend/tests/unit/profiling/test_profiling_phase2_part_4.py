class TestMultiUser(BaseTest):
    """Every user archives independently within one app."""

    @pytest.mark.parametrize(
        (
            "user_count",
            "flag_pattern",
            "expected_summary",
            "uid",
        ),
        _MULTI_USER_CASES,
    )
    def test_multi_user(
        self, user_count: int, flag_pattern: int, expected_summary: int, uid: int
    ) -> None:
        """Every user archives independently within one app."""
        profiler: UserProfiler = UserProfiler(":memory:", ":memory:", 3)
        for _ in range(3):
            for index in range(user_count):
                flagged = 1 if index % 2 == flag_pattern % 2 else 0
                profiler.record("app", f"u{index}", total_msgs=1, flagged_msgs=flagged)
            self.advance_days(1)
        stats = profiler.stats()
        assert stats["summary_count"] == expected_summary
        profiler.close()

class TestRatioGoldenMatrix(BaseTest):
    """The profiler reproduces the golden bad-content ratio."""

    @pytest.mark.parametrize(
        (
            "flagged",
            "blocked",
            "total",
            "expected",
            "uid",
        ),
        _RATIO_GOLDEN_MATRIX_CASES,
    )
    def test_ratio_golden_matrix(
        self, flagged: int, blocked: int, total: int, expected: float, uid: int
    ) -> None:
        """The profiler reproduces the golden bad-content ratio."""
        profiler: UserProfiler = UserProfiler(":memory:", ":memory:", 91)
        profiler.record("app", "u", total_msgs=total, flagged_msgs=flagged, blocked_msgs=blocked)
        assert profiler.get_ratio("app", "u") == expected
        profiler.close()

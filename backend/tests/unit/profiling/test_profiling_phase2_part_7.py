        """Repeated short windows produce the expected cycle count."""
        profiler: UserProfiler = UserProfiler(":memory:", ":memory:", 2)
        for _ in range(cycle_count * 2):
            profiler.record("app", "u", total_msgs=1, flagged_msgs=pattern % 2)
